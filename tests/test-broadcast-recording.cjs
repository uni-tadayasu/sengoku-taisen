'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {createHash} = require('node:crypto');
require('../music.js');
const root=path.resolve(__dirname,'..');
const record=JSON.parse(fs.readFileSync(path.join(root,'assets/music/broadcast-master.json'),'utf8'));
const track=global.SENGOKU_BROADCAST_TRACK;
const bytes=fs.readFileSync(path.join(root,record.path));
assert.equal(record.sourceName,'00004.mp3');
assert.equal(record.sourceSha256,'e49be4d9323bb82de5bb5b7044fedd3a37cba026a1450f2c484c1460c35f1656');
assert.equal(record.sha256,record.sourceSha256);
assert.equal(createHash('sha256').update(bytes).digest('hex'),record.sha256,'The corrected MP3 must be preserved byte for byte.');
assert.equal(bytes.length,4631901);
assert.equal(record.bytes,bytes.length);
assert.equal(track.recording,record.path);
assert.equal(track.duration,202.12);
assert.equal(track.duration,record.decodedDuration);
assert.equal(track.sampleRate,48000);
assert.equal(track.recordingOnly,true);
assert.equal(global.SENGOKU_BROADCAST_PLAYLIST[0],track);
assert.equal(global.SENGOKU_BROADCAST_PLAYLIST.length,21);
console.log('PASS corrected 00004.mp3 is preserved exactly, decodes to 202.12 seconds, and leads the broadcast programme.');
