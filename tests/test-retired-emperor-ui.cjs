const assert=require('node:assert/strict'),fs=require('node:fs'),court=require('../public-court.js');
const retired={title:'上皇',kind:'retired-emperor'};
court.clear();
assert.deepEqual(court.normalize(retired),retired);
assert.equal(court.normalize({title:'上皇',kind:'emperor'}),null);
assert.equal(court.normalize({title:'天皇',kind:'retired-emperor'}),null);
const badge=court.badge({courtOffice:retired});
assert.match(badge,/aria-label="役職：上皇"/);
assert.match(badge,/public-court-retired-emperor/);
assert.match(badge,/data-court-seal="moon"/);
assert.match(badge,/public-court-linework-only/);
assert.doesNotMatch(badge,/<img/,'The retired Emperor has complete inline artwork without a missing external asset');
assert.match(fs.readFileSync(require.resolve('../public-court.css'),'utf8'),/\.public-court-icon\s*>\s*\.public-court-linework-only\s*\{display:block\}/);
court.update({user:{id:'u_retired',courtOffice:retired}});assert.equal(court.text('u_retired'),'上皇');
const old=court.beginRequest(),current=court.beginRequest();
court.update({user:{id:'u_retired',courtOffice:{title:'天皇',kind:'emperor'}}},{requestSequence:current});
court.update({user:{id:'u_retired',courtOffice:retired}},{requestSequence:old});assert.equal(court.text('u_retired'),'天皇');
court.update({user:{id:'u_retired',courtOffice:null}});assert.equal(court.badge('u_retired'),'');
const regent={title:'摂政',kind:'regent'};assert.deepEqual(court.normalize(regent),regent);assert.equal(court.normalize({title:'摂政',kind:'emperor'}),null);
const regentBadge=court.badge({courtOffice:regent});assert.match(regentBadge,/aria-label="役職：摂政"/);assert.match(regentBadge,/data-court-seal="sceptre"/);assert.doesNotMatch(regentBadge,/<img/);
court.update({user:{id:'u_regent',courtOffice:regent}});assert.equal(court.text('u_regent'),'摂政');court.update({user:{id:'u_regent',courtOffice:{title:'天皇',kind:'emperor'}}});assert.equal(court.text('u_regent'),'天皇');
console.log('Retired Emperor badge, verified title, and stale response checks passed.');
