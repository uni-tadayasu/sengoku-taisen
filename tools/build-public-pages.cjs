function tagAttributes(tag) {
  return Object.fromEntries([...tag.matchAll(/([\w:-]+)\s*=\s*(["'])(.*?)\2/g)].map(match => [match[1], match[3]]));
}

function replaceHeadTag(html, tagName, matches, replacement) {
  let found = false;
  html = html.replace(new RegExp(`<${tagName}\\b[^>]*>`, 'gi'), tag => {
    if (!matches(tagAttributes(tag))) return tag;
    if (found) return '';
    found = true;
    return replacement;
  });
  return found ? html : html.replace('</head>', `  ${replacement}\n</head>`);
}

function withSelectionAssets(html, prefix = '') {
  html = replaceHeadTag(html, 'link', attrs => attrs.rel === 'stylesheet' && /(?:^|\/)selection-lock\.css(?:\?|$)/.test(attrs.href || ''), `<link rel="stylesheet" href="${prefix}selection-lock.css?v=${release}">`);
  const script = `<script defer src="${prefix}selection-lock.js?v=${release}"></script>`;
  let found = false;
  html = html.replace(/<script\b([^>]*)>[\s\S]*?<\/script>/gi, (tag, attributes) => {
    if (!/(?:^|\/)selection-lock\.js(?:\?|$)/.test(tagAttributes(attributes).src || '')) return tag;
    if (found) return '';
    found = true;
    return script;
  });
  return found ? html : html.replace('</head>', `  ${script}\n</head>`);
}

function withButtonArtwork(html, href) {
  return replaceHeadTag(html, 'link', attrs => attrs.rel === 'stylesheet' && /(?:^|\/)button-artwork\.css(?:\?|$)/.test(attrs.href || ''), `<link rel="stylesheet" href="${href}?v=${release}">`);
}

