'use strict';

// Keep classic script execution and CSS cascade order while serving fewer files.
// All bundles live beside their sources so relative URLs in CSS remain valid.
const fs = require('node:fs');
const path = require('node:path');
const {createHash} = require('node:crypto');
const {transformSync} = require('esbuild');
const {minify_sync} = require('terser');
const {packOfficerRoster} = require('./pack-officer-roster.cjs');
const {gzipSync} = require('node:zlib');
const {compactCss} = require('./compact-css.cjs');
const groups = require('./game-entry.json');
const root = path.join(__dirname, '..');
const check = process.argv.includes('--check');
const mismatches = [];
const stats = [];
function writeIfChanged(name, data) {
  const filename = path.join(root, name);
  if (fs.existsSync(filename) && fs.readFileSync(filename, 'utf8') === data) return;
  if (check) mismatches.push(name);
  else fs.writeFileSync(filename, data);
}
let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
function setRevision(name, bytes) {
  const hash = createHash('sha256').update(bytes).digest('hex').slice(0,12);
  const marker = new RegExp(name.replaceAll('.', '\\.') + '\\?v=[\\w.-]+','g');
  if (!marker.test(html)) throw Error(`Missing entry URL in index.html: ${name}`);
  html = html.replace(marker, `${name}?v=${hash}`);
}
for (const [name, sources] of Object.entries(groups)) {
  const isScript = name.endsWith('.js');
  const source = sources.map(file => {
    const text = fs.readFileSync(path.join(root, file), 'utf8');
    return `/* ${file} */\n` + (file === 'officers-data.js' ? packOfficerRoster(text) : text);
  }).join(isScript ? '\n;\n' : '\n') + '\n';
  // Transform classic scripts without bundling or a module wrapper: their
  // globals, execution order and CSS cascade must remain unchanged. Keep
  // function names and public property names; never remove side effects.
  const result = transformSync(source, {
    loader: isScript ? 'js' : 'css', sourcefile: name,
    target: ['chrome90', 'firefox90', 'safari15'], charset: 'utf8',
    minify: !isScript, treeShaking: false,
    legalComments: 'inline'
  });
  if (result.warnings.length) throw Error(result.warnings.map(warning => warning.text).join('\n'));
  const code = isScript ? minify_sync(result.code, {
    module: false, toplevel: false, ecma: 2020,
    compress: {passes: 2, pure_getters: false, keep_fargs: true, drop_debugger: false},
    mangle: {toplevel: false},
    keep_fnames: true, keep_classnames: true,
    format: {comments: /^!|@preserve|@license|@cc_on/i}
  }).code + '\n' : compactCss(result.code);
  const data = '/* Generated by node tools/build-game-entry.cjs. Sources: tools/game-entry.json. */\n' + code;
  stats.push({file:name, sourceBytes:Buffer.byteLength(source), bytes:Buffer.byteLength(data), gzipBytes:gzipSync(data).length});
  writeIfChanged(name, data);
  setRevision(name, data);
}
setRevision('map-data.js', fs.readFileSync(path.join(root, 'map-data.js')));
writeIfChanged('index.html', html);
if (mismatches.length) throw Error(`Run node tools/build-game-entry.cjs to refresh ${mismatches.join(', ')}`);
if (process.argv.includes('--stats')) console.log(JSON.stringify({bundles:stats,totalBytes:stats.reduce((sum,item)=>sum+item.bytes,0),totalGzipBytes:stats.reduce((sum,item)=>sum+item.gzipBytes,0)},null,2));
