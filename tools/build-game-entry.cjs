'use strict';

// Keep classic script execution and CSS cascade order while serving fewer files.
// All bundles live beside their sources so relative URLs in CSS remain valid.
const fs = require('node:fs');
const path = require('node:path');
const {createHash} = require('node:crypto');
const groups = require('./game-entry.json');
const root = path.join(__dirname, '..');
const check = process.argv.includes('--check');
const mismatches = [];
function writeIfChanged(name, data) {
  const filename = path.join(root, name);
  if (fs.existsSync(filename) && fs.readFileSync(filename, 'utf8') === data) return;
  if (check) mismatches.push(name);
  else fs.writeFileSync(filename, data);
}
let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
function setRevision(name, bytes) {
  const hash = createHash('sha256').update(bytes).digest('hex').slice(0,12);
  const marker = new RegExp(name.replaceAll('.', '\\.') + '\\?v=[\\w.-]+','g');
  if (!marker.test(html)) throw Error(`Missing entry URL in index.html: ${name}`);
  html = html.replace(marker, `${name}?v=${hash}`);
}
for (const [name, sources] of Object.entries(groups)) {
  const isScript = name.endsWith('.js');
  const data = '/* Generated by node tools/build-game-entry.cjs. Edit the listed source files. */\n' +
    sources.map(file => `/* ${file} */\n` + fs.readFileSync(path.join(root, file), 'utf8')).join(isScript ? '\n;\n' : '\n') + '\n';
  writeIfChanged(name, data);
  setRevision(name, data);
}
setRevision('map-data.js', fs.readFileSync(path.join(root, 'map-data.js')));
writeIfChanged('index.html', html);
if (mismatches.length) throw Error(`Run node tools/build-game-entry.cjs to refresh ${mismatches.join(', ')}`);
