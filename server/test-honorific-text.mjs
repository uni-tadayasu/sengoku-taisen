// These 20 examples are held out of the training inventory. Abstention is
// allowed for ambiguous prose; it must never relabel a report as an order.
const heldout={
  request:['木を集めて','砦を直してほしい','東門には来ないで','返答を頼む'],
  question:['何時に合流する','どの城を攻める','誰が先に渡る','いつ帰る'],
  statement:['私は二条城へ向かう','弓兵は戻らない','明日こちらから連絡する','城にもう着いた'],
  greeting:['朝だね、おはよう','いつもありがとう','本当に助かったよ','それではまたよろしく'],
  label:['守備隊の編成案','明日の援軍配置表','西の城下町','来月の建設計画']
};
let correct=0,abstained=0;
for(const [intent,inputs] of Object.entries(heldout))for(const input of inputs){
  const answer=japaneseIntent(input);
  if(answer==='unknown')abstained++;
  else{assert.equal(answer,intent,input);correct++;}
}
assert(correct>=16);assert.equal(correct+abstained,20);
console.log('Honorific conversion passed '+grammar.length+' grammatical and '+literals.length+' literal cases. Held-out intents: '+correct+' correct, '+abstained+' abstentions, 0 misclassifications.');
